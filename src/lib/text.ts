function findCanonical(input: string): string | null {
  const s = input.toLowerCase();
  for (const group of CATEGORY_SYNONYMS) {
    for (const m of group.match) {
      if (s.includes(m)) return group.canonical;
    }
  }
  return null;
}

/**
 * Normalize a category for STORAGE: trim + collapse whitespace + consistent
 * case ("продукты"/"ПРОДУКТЫ" → "Продукты"). Does NOT merge synonyms — brand
 * names like "Ростикс", "Бургер Кинг" are kept as the user typed them, so the
 * user can see and edit each expense's real category. Merging for the chart
 * is done separately by {@link chartCategory}.
 */
export function normalizeCategory(input: string): string {
  const t = (input ?? "").trim().replace(/\s+/g, " ");
  if (!t) return "Прочее";
  const capped = t.charAt(0).toUpperCase() + t.slice(1).toLowerCase();
  return capped.slice(0, 40);
}

/**
 * Map a stored category to its canonical CHART group via the synonym table
 * (e.g. "Ростикс", "Бургер Кинг", "Вкусно и точка" → "Рестораны"). Used only
 * for chart grouping — the stored category is preserved as the user entered it.
 * If no synonym matches, returns the case-normalized original.
 *
 * For backward-compat with the dashboard's English category keys ("products",
 * "restaurants", …) the English key is mapped to its Russian canonical form first.
 */
const KEY_TO_CANONICAL: Record<string, string> = {
  products: "Продукты",
  utilities: "Коммуналка",
  transport: "Транспорт",
  restaurants: "Рестораны",
  household: "Бытовые товары",
  leisure: "Развлечения",
  other: "Прочее",
};

export function chartCategory(input: string): string {
  const t = (input ?? "").trim().replace(/\s+/g, " ");
  if (!t) return "Прочее";
  if (KEY_TO_CANONICAL[t]) return KEY_TO_CANONICAL[t];
  const canonical = findCanonical(t);
  if (canonical) return canonical;
  return normalizeCategory(t);
}

/** Human-readable period label for a number of days. */
export function formatPeriod(days: number): string {
  if (days === 1) return "1 день";
  if (days === 7) return "1 неделя";
  if (days === 30) return "1 месяц";
  if (days === 90) return "3 месяца";
  if (days === 180) return "6 месяцев";
  if (days === 365) return "1 год";
  if (days === 730) return "2 года";
  if (days > 365 && days % 365 === 0) return `${days / 365} лет`;
  if (days >= 30 && days % 30 === 0) return `${days / 30} мес.`;
  return `${days} дн.`;
}

/**
 * Format money with up to 2 decimal places (cents/kopecks). Used for converted
 * amounts in non-round currencies (e.g. USD shows "12.34 $"). Trailing zeros
 * are kept (12.50, not 12.5) so cents are always visible for foreign currency.
 * For RUB (and other round displays) use formatMoney (no decimals).
 */
export function formatMoneyPrecise(amount: number, currency = "₽"): string {
  const THIN_SPACE = "\u202F";
  const sign = amount < 0 ? "-" : "";
  const abs = Math.abs(amount);
  const rounded = Math.round(abs * 100) / 100;
  const s = rounded.toFixed(2);
  const [intPart, decPart] = s.split(".");
  let grouped = "";
  for (let i = 0; i < intPart.length; i++) {
    if (i > 0 && (intPart.length - i) % 3 === 0) grouped += THIN_SPACE;
    grouped += intPart[i];
  }
  return `${sign}${grouped}.${decPart} ${currency}`;
}
